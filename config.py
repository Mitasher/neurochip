"""
Централизованная конфигурация эксперимента по SEU-устойчивости.

Эксперимент сравнивает влияние однобитовых сбоев (Single Event Upset)
на двух архитектурах:
  * фон-Нейман  — обычный микроконтроллер (numpy-модель: float32 / int8 веса,
                  регистры-аккумуляторы, счётчик цикла как «PC»);
  * нейроморф    — чип AltAI (тернарные веса {-1,0,1}, спайковая бинаризация,
                  утечка мембраны).

Все общие константы, размеры задачи, цели битфлипа и пути собраны здесь,
чтобы не дублировать их по модулям.
"""

from __future__ import annotations

import os
import numpy as np


# ============================================================
# Воспроизводимость
# ============================================================
RANDOM_SEED: int = 42


def set_global_seed(seed: int = RANDOM_SEED) -> None:
    """Зафиксировать seed для numpy и стандартного random ради повторяемости."""
    import random
    np.random.seed(seed)
    random.seed(seed)
    os.environ['PYTHONHASHSEED'] = str(seed)


# ============================================================
# Размеры задачи
# ============================================================
# Задача мала намеренно: один тернарный слой укладывается в одно ядро AltAI,
# что позволяет валидировать numpy-модель нейроморфа против реального golden model.
IN_DIM: int = 16          # размерность входного вектора x
OUT_DIM: int = 4          # число выходов слоя = число классов (для классификатора)
NUM_CLASSES: int = OUT_DIM

# Входные спайки бинарные {0,1} — естественно ложатся в prepare_spikes() AltAI.
INPUT_BINARY: bool = True


# ============================================================
# Параметры эксперимента SEU
# ============================================================
N_TRIALS: int = 100       # число эмуляций битфлипа на каждую (алгоритм × платформа × цель)

# Сколько инъекций в синапс прогнать на РЕАЛЬНОМ эмуляторе чипа AltAI.
# Каждая инъекция = пересборка placed-конфига под повреждённые веса (~18-24 с),
# поэтому здесь намеренно меньше прогонов, чем N_TRIALS на быстрых numpy-моделях.
# Это полноценная проверка «прямо на чипе», а не имитация.
N_CHIP_SYNAPSE: int = 18

# Сколько примеров «вход → изменение → результат» сохранять/печатать на конфигурацию
# (для numpy-моделей; для чипа сохраняются ВСЕ прогоны — их мало).
TRACE_SAMPLES: int = 6

# Куда бить на фон-Неймановском МК.
VN_TARGETS: tuple[str, ...] = (
    'weight',         # бит в слове веса (RAM)
    'accumulator',    # бит в регистре-аккумуляторе во время свёртки W·x
    'pc',             # бит в счётчике цикла / «program counter» (поток управления)
)

# Куда бить на нейроморфе AltAI.
NM_TARGETS: tuple[str, ...] = (
    'synapse',        # бит в тернарном весе синапса (2-битное кодирование)
    'membrane',       # бит в мембранном потенциале нейрона (транзиент → утечка)
)

# Разрядности весов «обычного МК», которые прогоняем для полноты сравнения
# (float32 — ярче контраст по экспоненте; int8 — честнее против тернара AltAI).
VN_DTYPES: tuple[str, ...] = ('float32', 'int8')


# ============================================================
# Динамика нейроморфного нейрона (LIF / leaky integrate-and-fire)
# ============================================================
N_TICKS: int = 24         # число тиков симуляции на один вывод
LEAK: float = 0.5         # коэффициент утечки мембраны за тик (V *= LEAK перед интеграцией)
V_THRESHOLD: float = 0.5  # порог спайка по мембране (Heaviside)
# Бит, в который бьём при инъекции в мембрану, моделируется на знаковом int16-слове
MEMBRANE_BITS: int = 16


# ============================================================
# Пороги «фатальности» сбоя
# ============================================================
# Выход считается фатальным на МК, если по модулю превысил порог (переполнение
# экспоненты float → inf/огромное число) либо стал inf/nan.
FATAL_ABS_THRESHOLD: float = 1e6


# ============================================================
# Валидация против реального AltAI golden model (опционально)
# ============================================================
# Построение placed-конфига через Placer медленно и весит сотни МБ, поэтому
# валидация numpy-модели нейроморфа против реального чипа делается отдельно и
# кэшируется. Основной прогон 100 эмуляций идёт на быстрой numpy-модели.
ALTAI_CACHE_DIR: str = '.altai_cache'
ALTAI_MODEL_PATH: str = os.path.join(ALTAI_CACHE_DIR, 'ternary_layer.h5')
ALTAI_CONFIG_PATH: str = os.path.join(ALTAI_CACHE_DIR, 'ternary_layer_snn.json')
ALTAI_VALIDATION_SAMPLES: int = 30   # сколько случайных входов сверить с golden model


# ============================================================
# Пути результатов
# ============================================================
RESULTS_DIR: str = 'results'
REPORT_JSON_PATH: str = os.path.join(RESULTS_DIR, 'seu_report.json')


# Имена классов для отчёта по пороговому классификатору
CLASS_NAMES: dict[int, str] = {i: f'class_{i}' for i in range(NUM_CLASSES)}
